"""Print (or save) the environment record for reproducibility.

Usage:
  python src/check_env.py            # print to stdout
  python src/check_env.py --save     # also write docs/ENVIRONMENT.md
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import platform
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "ENVIRONMENT.md"

# packages that only matter for specific parts (absence is not an error)
OPTIONAL = ("playwright", "edge-tts", "pypdfium2", "torch", "transformers", "pyyaml")


def requirement_names() -> list[str]:
    names = []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        for sep in ("<", ">", "=", "!", "~", "["):
            line = line.split(sep, 1)[0]
        names.append(line.strip())
    return names


def version_of(dist: str) -> str:
    try:
        return md.version(dist)
    except md.PackageNotFoundError:
        return "not installed"


def gpu_note() -> str:
    try:
        import torch
        return f"CUDA available ({torch.cuda.get_device_name(0)})" if torch.cuda.is_available() else "CPU-only (torch installed, no CUDA device)"
    except (ImportError, OSError, RuntimeError):
        return "CPU-only (no torch/CUDA detected)"


def collect() -> list[tuple[str, str]]:
    rows = [
        ("Python", f"{platform.python_version()} ({sys.executable})"),
        ("Platform", platform.platform()),
        ("Processor", platform.processor() or "unknown"),
        ("CPU count", str(__import__("os").cpu_count())),
        ("GPU", gpu_note()),
        ("venv", sys.prefix != getattr(sys, "base_prefix", sys.prefix) and "yes (.venv)" or "no"),
        ("Project root", str(ROOT)),
        ("Git", shutil.which("git") and "git available" or "git not on PATH"),
    ]
    for name in requirement_names():
        rows.append((name, version_of(name)))
    for name in OPTIONAL:
        if name not in {r[0] for r in rows}:
            rows.append((f"{name} (optional)", version_of(name)))
    return rows


def render(rows: list[tuple[str, str]]) -> str:
    lines = [
        "# ENVIRONMENT",
        "",
        "Generated by `python src/check_env.py` — rerun after changing machines.",
        "",
        "| Package / field | Value |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in rows]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Record the environment")
    parser.add_argument("--save", action="store_true", help="write docs/ENVIRONMENT.md")
    args = parser.parse_args()

    rows = collect()
    width = max(len(k) for k, _ in rows)
    for key, val in rows:
        print(f"{key:<{width}}  {val}")
    print(f"\nPython {platform.python_version()}, {platform.platform()}, {gpu_note()}")

    if args.save:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(rows), encoding="utf-8")
        print(f"Saved {OUT}")


if __name__ == "__main__":
    main()
